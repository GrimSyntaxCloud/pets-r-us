const { test, before, after } = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
const { MongoMemoryServer } = require('mongodb-memory-server');
const { MongoStore } = require('connect-mongo');
const request = require('supertest');
const { randomBytes } = require('node:crypto');
const User = require('../models/users');
const Appointment = require('../models/appointments');
const { cleanup, RETENTION_MS } = require('../lib/retention');
let db, app, store, clock = new Date();
const password = 'fictional-test-password';
before(async () => {
  db = await MongoMemoryServer.create();
  await mongoose.connect(db.getUri('pets_r_us_test'));
  await require('../lib/prepare').prepare();
  store = MongoStore.create({ client: mongoose.connection.getClient(), dbName: mongoose.connection.name, collectionName: 'pets_sessions', autoRemove: 'disabled' });
  app = require('../app')({ store, secret: randomBytes(32).toString('hex'), now: () => clock });
});
after(async () => { await mongoose.disconnect(); if (db) await db.stop(); });
async function form(agent, path, body) {
  const page = await agent.get(path).expect(200);
  const token = page.text.match(/name="_csrf" value="([^"]+)"/)[1];
  return agent.post(path).type('form').send({ _csrf: token, ...body });
}
test('register, authenticate, save multiple appointments, edit safely, expire and preserve seed data', async () => {
  const agent = request.agent(app);
  await request(app).get('/registration').expect(200).then(r => assert.doesNotMatch(r.text, /Active Users|taylor@example/));
  await request(app).post('/registration').type('form').send({ txtUserName: 'bad' }).expect(403).then(r => { assert.match(r.text, /This form expired/); assert.doesNotMatch(r.text, /ReferenceError/); });
  assert.equal((await form(agent, '/registration', { txtUserName: 'visitor', email: 'visitor@example.com', password, isDemo: true })).status, 302);
  let user = await User.findOne({ username: 'visitor' }).select('+passwordHash');
  assert.equal(user.isDemo, false);
  assert.equal(+user.expiresAt - +user.createdAt, RETENTION_MS);
  assert.notEqual(user.passwordHash, password);
  const expiry = +user.expiresAt;
  const appointment = { firstName: 'Test', lastName: 'Visitor', email: 'visitor@example.com', service: 'boarding', isDemo: true, userId: '000000000000000000000002' };
  for (let i = 0; i < 2; i++) assert.equal((await form(agent, '/appointment', appointment)).status, 302);
  assert.equal(await Appointment.countDocuments({ userId: user._id, isDemo: false }), 2);
  const saved = await Appointment.findOne({ userId: user._id });
  assert.equal(+saved.expiresAt, expiry);
  await agent.get('/profile').expect(200).then(r => assert.match(r.text, /Test Visitor/));
  const other = request.agent(app);
  assert.equal((await form(other, '/registration', { txtUserName: 'other', email: 'other@example.com', password })).status, 302);
  await other.get('/profile').expect(200).then(r => assert.doesNotMatch(r.text, /visitor@example.com|Test Visitor/));
  await request(app).get('/users/visitor').expect(404);
  assert.equal((await form(agent, '/edit', { username: 'renamed', email: 'updated@example.com', isDemo: true, expiresAt: '2099-01-01' })).status, 302);
  user = await User.findById(user._id);
  assert.equal(+user.expiresAt, expiry);
  assert.equal(user.isDemo, false);
  assert.equal((await form(other, '/edit', { username: 'renamed', email: 'other@example.com' })).status, 400);
  assert.equal((await form(agent, '/appointment', { ...appointment, service: 'invalid' })).status, 400);
  const profile = await agent.get('/profile');
  await agent.post('/logout').type('form').send({ _csrf: profile.text.match(/name="_csrf" value="([^"]+)"/)[1] }).expect(302);
  await agent.get('/profile').expect(302);
  assert.equal((await form(agent, '/login', { username: 'renamed', password: 'incorrect-password' })).headers.location, '/login?failed=1');
  assert.equal((await form(agent, '/login', { username: 'renamed', password })).headers.location, '/profile');
  clock = new Date(expiry - 1);
  await agent.get('/profile').expect(200);
  clock = new Date(expiry);
  await agent.get('/profile').expect(302);
  assert.equal((await form(agent, '/login', { username: 'renamed', password })).headers.location, '/login?failed=1');
  const result = await cleanup({ User, Appointment }, clock);
  assert.equal(result.users, 2);
  assert.equal(result.appointments, 2);
  assert.equal(await Appointment.countDocuments({ isDemo: true }), 1);
  await request(app).get('/demo').expect(200).then(r => assert.match(r.text, /Taylor Sample/));
});
test('service pages render and missing pages return 404', async () => {
  for (const path of ['/', '/grooming', '/boarding', '/training', '/login']) await request(app).get(path).expect(200);
  await request(app).get('/missing').expect(404);
});
test('unsafe or incomplete server configuration fails closed', () => {
  assert.throws(() => require('../app')({ store, secret: 'short' }));
  assert.throws(() => require('../app')({ secret: 'a'.repeat(32) }));
  const { localUri } = require('../lib/local-database');
  const original = process.env.MONGODB_URI;
  process.env.MONGODB_URI = 'mongodb://example.invalid/pets_r_us_remote';
  assert.throws(localUri);
  if (original === undefined) delete process.env.MONGODB_URI; else process.env.MONGODB_URI = original;
});
